// 모든 스펙이 끝난 뒤 DB 커넥션 풀을 한 번 닫는다.
//
// 예전에는 스펙 파일마다 afterAll에서 db.pool.end()를 불렀다. workers: 1이라 모든 스펙이
// 한 프로세스를 공유하는데, 먼저 끝난 파일이 풀을 닫아버리면 **뒤에 오는 파일이** 통째로
// "Cannot use a pool after calling end on the pool"으로 죽었다(2026-09-03 실제로 겪었다).
// 더 고약한 것은 실패가 죽은 파일 쪽에 찍힌다는 점이다 — 원인은 앞에서 끝난 다른 파일인데
// 보는 사람은 엉뚱한 코드를 뒤진다.
//
// 닫는 일 자체는 여전히 필요하다(안 닫으면 워커가 유휴 소켓을 들고 늦게 끝난다). 다만
// "전부 끝난 뒤 한 번"이 맞는 자리라 여기로 옮겼다.
module.exports = async () => {
  const db = require('../db');
  await db.pool.end().catch(() => {});
};
