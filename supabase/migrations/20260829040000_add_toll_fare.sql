-- 경로 총 통행료(카카오) 저장.
--
-- 지금까지 이 값은 계산만 하고 버렸다 — 챗봇 요금안내에만 쓰고 오더에 남기지 않았다.
-- 그런데 통행료는 **청구되는 경우가 있는 값**이라(일반 통행료를 '실비 정산'으로 둔 법인),
-- 저장하지 않으면 정산할 때 다시 알 방법이 없다. 기사 영수증을 기다리는 수밖에 없었다.
--
-- 카카오는 요금소별 금액을 주지 않는다(실측: summary.fare.toll 합계 하나뿐). 그래서 이 값은
-- "그 경로를 그대로 달렸을 때의 총 통행료"이고, 특수교량 요금이 이미 그 안에 들어 있다.
-- 그 사실이 청구 규칙을 가른다(lib/orderCreate.js tollChargeFor 주석 참고):
--
--   일반 통행료 '포함'  → 특수교량 금액만 청구 (총액을 쓰면 포함분까지 이중 청구)
--   일반 통행료 '실비'  → 총 통행료를 청구  (특수교량이 이미 포함돼 있어 따로 더하면 이중 청구)
