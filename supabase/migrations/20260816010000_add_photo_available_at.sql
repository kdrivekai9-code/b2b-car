-- 콜마너 탁송사진이 "실제로 열리기 시작한 시각"을 기록한다.
--
-- 왜: 링크가 저장되는 시각과 그 파일이 실제로 열리는 시각이 다르다. 실측(OID1237)에서
-- 2026-08-13 20:55에 링크 26장이 저장됐는데, 다음 날 10시에도 전부 404였고 8/16에는 200이었다.
-- 그래서 완료 직후 나가는 통보에 사진을 실으려 하면 한 장도 못 싣는다(실제로 "5장 중 0장 발송").
--
-- 문제는 그 지연이 얼마인지 아무도 모른다는 것이다. 표본이 1건뿐이고 그마저 "13시간 뒤에도
-- 없었다"까지만 알 뿐 언제 올라왔는지는 모른다. 몇 분이면 통보를 그만큼 늦추면 되고, 몇 시간이면
-- 사진이 준비됐을 때 따로 알리는 편이 맞고, 항상 반나절이면 알려도 고객이 이미 관심이 없다 —
-- 대응이 완전히 갈리는데 근거가 없다.
--
-- 그래서 먼저 재기만 한다. 이 컬럼이 채워지면 "저장 시각 → 열린 시각" 분포를 실제로 볼 수 있고,
-- 그때 통보 방식을 정한다. 통보를 보내는 기능은 아직 넣지 않는다.
alter table order_callmaner_photos
  add column if not exists available_at timestamptz;

-- 아직 확인되지 않은 사진만 골라내는 조회가 매번 돈다(크론). 확인이 끝난 행은 대상에서 빠진다.
create index if not exists idx_order_callmaner_photos_pending_check
  on order_callmaner_photos(order_id, phase)
  where available_at is null;
