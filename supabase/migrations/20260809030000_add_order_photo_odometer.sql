-- 계기판 주행거리 — 기사가 사진을 올릴 때 함께 적는 값.
--
-- Phase 3 범위의 "계기판 주행거리 필드화". 지금은 계기판 사진만 남아서, 주행거리를 알려면
-- 사람이 사진을 열어 숫자를 읽어야 한다. 고객이 "몇 km 뛰었나요"라고 물으면 상담원이 사진을
-- 찾아 확인하고 답하는 일이 반복됐다.
--
-- 오더가 아니라 사진에 붙인다. 탁송은 출발·도착 계기판을 각각 찍고 구간 릴레이는 기사가 여럿이라,
-- 오더에 컬럼 두 개(출발/도착)를 두면 구간이 늘어날 때마다 자리가 모자란다. 사진마다 값을 두면
-- 주행거리는 최댓값 − 최솟값으로 언제든 구할 수 있다.
--
-- NULL은 "안 적었다"는 뜻이다. 계기판이 아닌 사진(차량 외관·인수증)에는 값이 없는 게 정상이라
-- 필수로 두지 않는다.
alter table order_photos
  add column if not exists odometer_km integer;
