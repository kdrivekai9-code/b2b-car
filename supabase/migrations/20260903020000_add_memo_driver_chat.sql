-- 기사 챗봇 전달사항 — 상담원이 기사에게 직접 보내는 메모.
--
-- 기존 memo_customer(기사 전달사항)와 성격이 다르다.
--   memo_customer     — 고객이 접수할 때 쓴 요청. 콜마너 적요1로 나가고 **100Byte에 잘린다.**
--   memo_driver_chat  — 우리가 기사 채팅으로 보내는 말. 길이 제한이 없다.
--
-- 나누는 이유가 그 제한이다. 적요1이 100Byte라 정작 필요한 안내가 밀려 잘리는데(실측: 기사
-- 메모의 24.4%가 예산 초과), 채팅은 우리 화면이라 제한이 없다. 한 칸에 섞으면 어느 쪽 규칙을
-- 따라야 할지 알 수 없고, 길게 쓰면 콜마너로 나가는 쪽이 잘린다.
--
-- 고객은 쓰지도 보지도 않는다. 상담원이 기사에게 하는 말이라 청구·정산과도 무관하다.
alter table orders add column if not exists memo_driver_chat text;
