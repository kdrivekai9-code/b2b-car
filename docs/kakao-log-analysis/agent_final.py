import json, re, collections, random

recs = json.load(open('msgs.json', encoding='utf-8'))
ag = [r for r in recs if r['role'] == '상담원']

# 단일 라벨(우선순위 순). 위에서부터 먼저 맞는 것으로 확정.
apats = [
    ('사진 첨부(본문 없음)', r'^\s*사진(\s*\d+\s*장)?\s*(메시지가 삭제되었습니다\.?)?\s*$'),
    ('출발/도착 사진 캡션', r'(출발\s*사진|도착\s*사진|출발전|도착후|계기판)'),
    ('기사 배정 통보', r'(배정되었|배정\s*기사|기사명\s*[:：]|기사\s*01\d{8,9}|기사\s*010-)'),
    ('기사 미배정 안내', r'(미배정|배정\s*전입니다|배정되는대로)'),
    ('접수 확인 ack', r'(접수하겠습니다|접수했습니다|접수완료|접수 하겠습니다)'),
    ('보험 가입 처리', r'(가입하겠습니다|가입완료|책임보험)'),
    ('취소/변경 처리', r'(취소하겠습니다|취소되었|변경하겠습니다|변경완료|수정하겠습니다|변경\s*진행|로 진행하겠습니다)'),
    ('진행상태 통보', r'(출발했습니다|출발합니다|출발\s*예정|도착하였|도착했습니다|도착\s*예정|이동\s*중|완료하였|완료되었)'),
    ('주행거리 보고', r'(주행거리|키로수|\bkm\b)'),
    ('요금/정산/과태료', r'(요금|금액|비용|정산|세금계산서|계산서|입금|청구|단가|통행료|과태료|주유비)'),
    ('서류 안내', r'(등록증|인감|위임장|서류)'),
    ('사과/지연 설명', r'(죄송|지연|늦어|양해)'),
    ('단순 응대', r'^[\s]*(네+[~\s.!]*|넵+[~\s.!]*|감사합니다[\s.!~]*|알겠습니다[\s.!]*|확인(했|하겠)습니다[\s.!]*|전달하겠습니다[\s.!]*)+$'),
]
lab = collections.Counter(); un = []
for r in ag:
    for k, p in apats:
        if re.search(p, r['text']):
            lab[k] += 1
            break
    else:
        lab['미분류'] += 1
        un.append(r['text'])
print('[상담원 메시지 단일라벨 분류] 총 %d' % len(ag))
for k, _ in apats:
    print('  %-20s %5d  %5.1f%%' % (k, lab[k], 100 * lab[k] / len(ag)))
print('  %-20s %5d  %5.1f%%' % ('미분류', lab['미분류'], 100 * lab['미분류'] / len(ag)))

# 자동화 가능성 등급
auto = {
    '완전자동(룰/시스템 데이터로 즉시 응답 가능)': ['접수 확인 ack', '기사 배정 통보', '기사 미배정 안내', '진행상태 통보', '주행거리 보고'],
    '자동화 가능(파일/데이터 파이프라인 필요)': ['사진 첨부(본문 없음)', '출발/도착 사진 캡션'],
    '반자동(조회는 자동, 판단은 사람)': ['취소/변경 처리', '보험 가입 처리', '요금/정산/과태료', '서류 안내'],
    '사람 필요': ['사과/지연 설명', '미분류'],
    '무의미 응대(제거 가능)': ['단순 응대'],
}
print('\n[자동화 등급별 상담원 메시지 비중]')
for g, ks in auto.items():
    n = sum(lab[k] for k in ks)
    print('  %-38s %5d  %5.1f%%' % (g, n, 100 * n / len(ag)))

print('\n=== 미분류 잔여 샘플 ===')
random.seed(11)
for t in random.sample(un, 25):
    print('•', t.replace('\n', ' ⏎ ')[:150])
json.dump(un, open('agent_unmatched2.json', 'w', encoding='utf-8'), ensure_ascii=False)
